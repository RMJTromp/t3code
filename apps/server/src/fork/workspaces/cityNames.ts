/**
 * A random unused city name. A taken name is any existing workspace, branch, or
 * folder, so a path is never reused while old threads still point at it.
 */
export function pickCityName(
  isTaken: (name: string) => boolean,
  random: () => number = Math.random,
): string {
  const free = CITY_NAMES.filter((name) => !isTaken(name));
  if (free.length > 0) return free[Math.floor(random() * free.length)]!;
  const base = CITY_NAMES[Math.floor(random() * CITY_NAMES.length)]!;
  for (let suffix = 2; ; suffix++) {
    const candidate = `${base}-${suffix}`;
    if (!isTaken(candidate)) return candidate;
  }
}
